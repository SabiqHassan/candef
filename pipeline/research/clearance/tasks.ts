/** The JSON package in an AI answer: one block, or PART k OF n blocks joined in order. */
export function packageFromAnswer(text: string): unknown {
  const blocks = [...text.matchAll(/```json[^\n]*\n([\s\S]*?)```/g)].map((m) => m[1]!);
  const isPackage = (v: unknown) =>
    typeof v === "object" && v !== null && ("package_version" in v || "packageversion" in v);
  // Parts are joined without the line breaks that fence each block (a split can fall mid-string).
  const joined = blocks.map((x) => x.replace(/^\n+|\n+$/g, "")).join("");
  for (const b of [...blocks, joined]) {
    try {
      const v = JSON.parse(b);
      if (isPackage(v)) return v;
    } catch {
      // a fragment, or prose
    }
  }
  // A bare JSON answer (some tools drop the fence).
  try {
    const v = JSON.parse(text.trim());
    if (isPackage(v)) return v;
  } catch {
    // not bare JSON
  }
  return undefined;
}

export interface IngestResult {
  ok: boolean;
  researcherId: string;
  card: string | null;
  findings: number;
  notes: string[];
  errors: string[];
  pkg: ResearcherPackage | null;
  json: string | null;
}

/** Validates an answer and stamps the researcher ID the owner chose (R-<tool>-<yyyymmdd>). */
export function ingestAnswer(
  text: string,
  tool: string,
  date: string,
  expectCard: string | null,
): IngestResult {
  const researcherId = `R-${tool
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")}-${date.replace(/-/g, "")}`;
  const fail = (errors: string[]): IngestResult => ({
    ok: false,
    researcherId,
    card: null,
    findings: 0,
    notes: [],
    errors,
    pkg: null,
    json: null,
  });
  if (!/^R-[a-z0-9-]+-\d{8}$/.test(researcherId) || /claude|muse/.test(researcherId))
    return fail([
      `tool "${tool}" cannot be used: give a short tool name, and never Claude or Muse (CANDEF's own researchers)`,
    ]);
  let raw = packageFromAnswer(text);
  if (raw === undefined) return fail(["no JSON package found in the answer"]);
  const notes: string[] = [];
  if (looksStripped(raw as never)) {
    const r = repairStripped(
      raw as never,
      vocabularyOf(z.toJSONSchema(PackageSchema, { unrepresentable: "any" }) as never),
    );
    raw = r.value;
    notes.push(`underscores restored (${r.notes.length} kinds)`);
  }
  const obj = raw as { researcher?: { id?: string; limitations?: string[] } };
  if (obj.researcher) {
    if (obj.researcher.id && obj.researcher.id !== researcherId)
      notes.push(`researcher.id "${obj.researcher.id}" replaced by ${researcherId}`);
    obj.researcher.id = researcherId;
  }
  const intake = intakePackage(raw);
  if (!intake.pkg) return fail(intake.errors.slice(0, 6));
  const card = intake.pkg.company.card_id;
  if (expectCard && card !== expectCard)
    return fail([`answer is for card ${card}, the task was ${expectCard}`]);
  const exposure = (intake.pkg.researcher.limitations ?? []).filter((l) =>
    /candef|prior (knowledge|context)|memory/i.test(l),
  );
  if (exposure.length)
    notes.push(
      `EXPOSURE: the researcher reports prior context (${exposure[0]!.slice(0, 120)}); add it to independence.json before it counts`,
    );
  return {
    ok: true,
    researcherId,
    card,
    findings: intake.pkg.findings.length,
    notes: [...notes, ...intake.notes],
    errors: [],
    pkg: intake.pkg,
    json: JSON.stringify(raw, null, 2),
  };
}

/**
 * Task packets for independent AI researchers that the owner runs by hand (policy section 3,
 * "bring your own AI"). The loop:
 *
 *   1. make:   for every company with blind-research homework, write one paste-ready prompt to
 *              research-cache/verify-tasks/<cohort>/outbox/. Each prompt is the company's existing,
 *              leak-checked blind prompt (no CANDEF values) with a short focus header that names
 *              only field IDs. Claude-only homework goes to claude-worklist.md instead.
 *   2. owner:  pastes a prompt into any AI tool (not Claude, which is CANDEF's own researcher),
 *              in a fresh chat with memory off, and saves the answer as a .md or .txt file in
 *              research-cache/verify-tasks/<cohort>/inbox/.
 *   3. ingest: validates the answer (the same intake and repairs as the blind returns), files it
 *              under the cohort's returns folder as researcher R-<tool>-<date>, and keeps the
 *              original. The next `clearance` run counts it as an independent researcher.
 *
 * Nothing here contacts any service. The owner chooses the tool, and runs it, every time.
 */
import type { BlindCard, ResearcherPackage } from "../blind";
import { intakePackage, ResearcherPackage as PackageSchema } from "../blind";
import { looksStripped, repairStripped, vocabularyOf } from "../blindRepair";
import { z } from "zod";
import { HOMEWORK, type HomeworkKind } from "./policy";
import type { ClearanceFile } from "./run";

/** Fields every inventory (completeness) task asks for: events, their money and their parties. */
export const INVENTORY_FIELDS = ["A15", "C01", "C02", "C03", "C04", "D01", "E07"];

export interface TaskPacket {
  taskId: string;
  card: string;
  fields: string[];
  inventory: boolean;
  /** Tools that already researched this card: suggest a different model family. */
  usedTools: string[];
  file: string;
  text: string;
}

/** Strips the old run header from a generated prompt (everything before the generator comment). */
export function promptBody(prompt: string): string {
  const i = prompt.indexOf("<!-- Generated by");
  return i >= 0 ? prompt.slice(i) : prompt;
}

export function taskHeader(p: Omit<TaskPacket, "file" | "text">, date: string): string {
  return [
    "# Run instructions (read before anything else)",
    "",
    `- **Task:** \`${p.taskId}\`, company card ${p.card} only (section 8).`,
    "- **Your researcher ID:** put `R-TOOL-" +
      date.replace(/-/g, "") +
      "` in `researcher.id`, with TOOL replaced by your tool's short name (for example `R-gemini-" +
      date.replace(/-/g, "") +
      "`). Put your real model name in `researcher.model_or_tool`.",
    `- **Focus:** research only these fields: ${p.fields.join(", ")}. For every other field ID add exactly one finding with status \`not_researched\` and notes "outside task focus".`,
    p.inventory
      ? "- **Completeness:** for financing events, investors, acquisitions and partnerships, list **every** event you can document from an original source, each as its own finding, not only the best-known ones. Say what you searched where you found nothing."
      : "- **Precision:** for each field, cite the original document (registry, filing, government record, the company's or counterparty's own page) that states the value, with the exact locator.",
    "- **Deliverable:** the complete package as **one JSON object in a single ```json code block** at the end of your answer. If it is too long, split it into consecutive ```json blocks, each preceded by `PART k OF n`; the user will reply `continue` if you are cut off.",
    "",
  ].join("\n");
}

/** One packet per card with blind-task or inventory work; Claude-only homework is listed apart. */
export function buildTaskPackets(
  file: ClearanceFile,
  cards: BlindCard[],
  promptFor: (card: string) => string | null,
  slugOf: (orgId: string) => string | null,
  date: string,
): { packets: TaskPacket[]; claudeWork: string; missingPrompts: string[] } {
  const packets: TaskPacket[] = [];
  const missingPrompts: string[] = [];
  for (const c of cards) {
    const slugs = new Set(c.orgSlugs);
    const recs = file.records.filter(
      (r) => slugs.has(slugOf(r.orgId) ?? "") && r.homework.some((h) => h.kind === "blind-task"),
    );
    const fields = new Set(recs.flatMap((r) => r.fields));
    const comp = file.completeness.find((x) => x.card === c.card);
    const inventory = !!comp?.categories.some(
      (x) =>
        x.category !== "government" &&
        (x.status === "no-independent-inventory" || x.status === "no-gap-found-1"),
    );
    if (inventory) INVENTORY_FIELDS.forEach((f) => fields.add(f));
    if (!fields.size) continue;
    const prompt = promptFor(c.card);
    if (!prompt) {
      missingPrompts.push(c.card);
      continue;
    }
    const taskId = `T-${date.replace(/-/g, "")}-${c.card}`;
    const usedTools = [
      ...new Set(comp?.categories.flatMap((x) => x.inventories.map((i) => i.researcher)) ?? []),
    ];
    const base = { taskId, card: c.card, fields: [...fields].sort(), inventory, usedTools };
    packets.push({
      ...base,
      file: `${taskId}.md`,
      text: taskHeader(base, date) + promptBody(prompt),
    });
  }
  const claudeKinds: HomeworkKind[] = [
    "verification-read",
    "find-original",
    "read-contradicting-source",
    "reread-copy",
    "fix-record",
    "link-capture",
    "adjudicate",
  ];
  const lines = [
    `# Claude worklist (${file.policy}, ${file.today})`,
    "",
    "Homework only a Claude session (or code) can do: reading originals, finding primary sources, fixing malformed proposed records. None of it is a decision for the owner. Records stay `proposed`; corrections are new proposed records.",
    "",
  ];
  for (const kind of claudeKinds) {
    const recs = file.records.filter((r) => r.homework.some((h) => h.kind === kind));
    if (!recs.length) continue;
    lines.push(`## ${kind}: ${HOMEWORK[kind].label} (${recs.length})`, "");
    for (const r of recs)
      lines.push(
        `- ${r.orgName}, \`${r.id}\` (${r.predicate ?? r.kind}): ${r.homework.find((h) => h.kind === kind)!.reason}`,
      );
    lines.push("");
  }
  return { packets, claudeWork: lines.join("\n"), missingPrompts };
}

